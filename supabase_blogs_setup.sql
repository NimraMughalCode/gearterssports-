-- 1. Create blogs table
CREATE TABLE IF NOT EXISTS public.blogs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT UNIQUE NOT NULL,
  excerpt TEXT,
  content TEXT NOT NULL,
  cover_image TEXT,
  category TEXT DEFAULT 'Boxing & Combat',
  author TEXT DEFAULT 'Gearters Sports Team',
  read_time TEXT DEFAULT '4 min read',
  is_featured BOOLEAN DEFAULT false,
  is_published BOOLEAN DEFAULT true,
  meta_title TEXT,
  meta_description TEXT,
  meta_keywords TEXT,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- 2. Indexes for maximum query performance & SEO slug lookups
CREATE INDEX IF NOT EXISTS blogs_slug_idx ON public.blogs(slug);
CREATE INDEX IF NOT EXISTS blogs_published_featured_idx ON public.blogs(is_published, is_featured);
CREATE INDEX IF NOT EXISTS blogs_created_at_idx ON public.blogs(created_at DESC);

-- 3. Row Level Security (RLS) setup
-- Enable RLS
ALTER TABLE public.blogs ENABLE ROW LEVEL SECURITY;

-- Allow public read access to published blogs
CREATE POLICY "Allow public read access to published blogs"
  ON public.blogs
  FOR SELECT
  USING (is_published = true);

-- Allow full access for anon/authenticated roles (matching existing products/categories pattern)
CREATE POLICY "Allow anon insert on blogs"
  ON public.blogs
  FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Allow anon update on blogs"
  ON public.blogs
  FOR UPDATE
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Allow anon delete on blogs"
  ON public.blogs
  FOR DELETE
  USING (true);

-- Also allow reading unpublished blogs if accessed from admin
CREATE POLICY "Allow anon read all blogs"
  ON public.blogs
  FOR SELECT
  USING (true);

