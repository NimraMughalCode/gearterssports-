-- 1. Create testimonials table
CREATE TABLE IF NOT EXISTS public.testimonials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name TEXT NOT NULL,
  client_title TEXT, -- e.g. "Boxing Gym Owner, USA"
  review_text TEXT,  -- optional written quote or feedback
  video_url TEXT NOT NULL, -- 16:9 video file URL (stored in product-images/testimonials/...)
  thumbnail_url TEXT, -- optional video poster/thumbnail
  rating INT DEFAULT 5, -- 1 to 5 stars
  display_order INT DEFAULT NULL, -- custom display order
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- 2. Indexes for sorting and fast retrieval
CREATE INDEX IF NOT EXISTS testimonials_display_order_idx 
ON public.testimonials (display_order ASC NULLS LAST, created_at DESC);

-- 3. Row Level Security (RLS) setup
ALTER TABLE public.testimonials ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access to testimonials"
  ON public.testimonials FOR SELECT USING (true);

CREATE POLICY "Allow anon insert on testimonials"
  ON public.testimonials FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow anon update on testimonials"
  ON public.testimonials FOR UPDATE USING (true);

CREATE POLICY "Allow anon delete on testimonials"
  ON public.testimonials FOR DELETE USING (true);
