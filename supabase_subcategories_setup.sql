-- 1. Create subcategories table (Relational link to categories)
CREATE TABLE IF NOT EXISTS public.subcategories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES public.categories(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  slug TEXT,
  display_order INT DEFAULT NULL,
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- 2. Indexes for fast category lookups and slug matches
CREATE INDEX IF NOT EXISTS subcategories_category_id_idx ON public.subcategories(category_id);
CREATE INDEX IF NOT EXISTS subcategories_slug_idx ON public.subcategories(slug);

-- 3. Row Level Security (RLS) setup
ALTER TABLE public.subcategories ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access to subcategories"
  ON public.subcategories FOR SELECT USING (true);

CREATE POLICY "Allow anon insert on subcategories"
  ON public.subcategories FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow anon update on subcategories"
  ON public.subcategories FOR UPDATE USING (true);

CREATE POLICY "Allow anon delete on subcategories"
  ON public.subcategories FOR DELETE USING (true);

-- 4. LOOP / POPULATE subcategories from categories.subcategories array
-- (Keeps existing categories.subcategories intact and extracts each string into a relational row)
INSERT INTO public.subcategories (category_id, title, slug)
SELECT 
  c.id, 
  TRIM(sub_name),
  LOWER(REGEXP_REPLACE(REGEXP_REPLACE(TRIM(sub_name), '[^a-zA-Z0-9]+', '-', 'g'), '^-+|-+$', '', 'g'))
FROM public.categories c,
     UNNEST(c.subcategories) AS sub_name
WHERE sub_name IS NOT NULL AND TRIM(sub_name) != ''
  AND NOT EXISTS (
    SELECT 1 FROM public.subcategories s 
    WHERE s.category_id = c.id AND LOWER(TRIM(s.title)) = LOWER(TRIM(sub_name))
  );

-- 5. Add subcategory_id column to products (Keep existing `subcategory` string column intact!)
ALTER TABLE public.products 
ADD COLUMN IF NOT EXISTS subcategory_id BIGINT REFERENCES public.subcategories(id) ON DELETE SET NULL;

-- 6. LOOP / UPDATE existing products to link them to their new subcategory_id
UPDATE public.products p
SET subcategory_id = s.id
FROM public.subcategories s
WHERE p.subcategory IS NOT NULL 
  AND LOWER(TRIM(p.subcategory)) = LOWER(TRIM(s.title))
  AND p.subcategory_id IS NULL;

-- 7. Create index on products(subcategory_id) for join performance
CREATE INDEX IF NOT EXISTS products_subcategory_id_idx ON public.products(subcategory_id);

